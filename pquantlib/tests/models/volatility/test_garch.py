# The Simplex x-convergence radius; see the module docstring for the derivation.
_SIMPLEX_ROOT_EPSILON = 1e-8
_SIMPLEX_REASON = (
    "Simplex(0.001) stops when the mean vertex-to-centroid distance of the simplex "
    "drops below EndCriteria.root_epsilon = tol_level = 1e-8 (garch.cpp:396-397, "
    "simplex.cpp:145/196-198), so the converged parameters are only determined to "
    "that radius; C++'s own two modes differ by 4e-8 in alpha on this same series."
)


class DummyOptimizationMethod(OptimizationMethod):
    """Evaluates the cost at the starting point and stops.

    # C++ parity: test-suite/garch.cpp:36-42. Used to observe the INITIAL
    # GUESS with no optimization on top of it, which is what separates the
    # deterministic half of the calibration from the Simplex search.
    """

    def minimize(self, problem: Problem, end_criteria: EndCriteria) -> Type:
        del end_criteria
        problem.set_function_value(problem.value(problem.current_value))
        return Type.None_


@pytest.fixture(scope="module")
def garch(cpp: dict[str, Any]) -> dict[str, Any]:
    return cpp["garch"]


@pytest.fixture(scope="module")
def returns(garch: dict[str, Any]) -> list[float]:
    return list(garch["series"])


@pytest.fixture(scope="module")
def series(garch: dict[str, Any], returns: list[float]) -> TimeSeries[float]:
    return TimeSeries[float].from_first_date(Date(garch["start_serial"]), returns)


def _assert_calibration(actual: Garch11, expected: dict[str, Any], *, tier: str) -> None:
    if tier == "tight":
        tolerance.tight(actual.alpha(), expected["alpha"])
        tolerance.tight(actual.beta(), expected["beta"])
        tolerance.tight(actual.omega(), expected["omega"])
        tolerance.tight(actual.lt_vol(), expected["lt_vol"])
    else:
        for got, want in (
            (actual.alpha(), expected["alpha"]),
            (actual.beta(), expected["beta"]),
            (actual.omega(), expected["omega"]),
            (actual.lt_vol(), expected["lt_vol"]),
        ):
            tolerance.custom(
                got, want, abs_tol=_SIMPLEX_ROOT_EPSILON, rel_tol=0.0, reason=_SIMPLEX_REASON
            )
    tolerance.tight(actual.log_likelihood(), expected["log_likelihood"])
    assert int(actual.mode()) == expected["mode"]


