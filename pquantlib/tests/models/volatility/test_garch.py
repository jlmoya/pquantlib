"""Cross-validation of Garch11 against C++ v1.43.

# C++ parity: ql/models/volatility/garch.{hpp,cpp} @ v1.43.
# Reference: migration-harness/cpp/probes/v143_models_volatility/probe.cpp,
# ``emitGarch``.

The input series is 400 points generated by the upstream test-suite's own
generator (``MersenneTwisterUniformRng(48)`` + ``InverseCumulativeNormal``
driving a ``Garch11(0.2, 0.3, 0.4)``, test-suite/garch.cpp:89-99) and is
carried IN the reference JSON, so both sides read identical doubles rather
than having to reproduce the RNG.

Tolerance tiers used here
-------------------------
Everything that is pure arithmetic — ``to_r2``, the autocovariances, the
static ``cost_function``, ``forecast``, ``calculate``, and the *initial
guesses* — is asserted at TIGHT.

The four fully-optimized ``alpha`` / ``beta`` / ``omega`` triples are not,
and the bound used is derived rather than chosen: ``calibrate_r2`` runs
``Simplex(0.001)`` under ``EndCriteria(10000, 500, 1e-8, 1e-8, 1e-8)``
(garch.cpp:396-397), and ``Simplex::minimize`` stops when the mean Euclidean
distance of the simplex vertices from their centroid falls below
``root_epsilon`` — i.e. 1e-8 (simplex.cpp:145/196-198, mirrored in
pquantlib/math/optimization/simplex.py). The converged point is therefore
only pinned to a radius of 1e-8 in parameter space, and that is exactly what
C++ itself shows on this series: its ``MomentMatchingGuess`` and
``GammaGuess`` answers differ from each other by 4e-8 in ``alpha`` while
agreeing on ``logLikelihood`` to 4e-16. So the parameters are checked at
``abs_tol = 1e-8`` (the optimizer's own stated x-resolution) and the
log-likelihood — the quantity that IS determined — stays at TIGHT.
"""

