@pytest.mark.parametrize(
    ("mode", "guess_key"),
    [
        (Garch11Mode.MomentMatchingGuess, "guess_moment_matching"),
        (Garch11Mode.BestOfTwo, "guess_best_of_two"),
        (Garch11Mode.DoubleOptimization, "guess_double_optimization"),
    ],
)
def test_a_failing_optimizer_falls_back_to_the_initial_guess(
    mode: Garch11Mode,
    guess_key: str,
    garch: dict[str, Any],
    series: TimeSeries[float],
) -> None:
    """# C++ parity: garch.cpp:450-459 and :471/:483.

    When every optimization attempt throws, C++ keeps the initial guess and
    returns a NULL ``Problem``, which makes ``calibrate`` fall back to
    ``-costFunction(begin, end)`` over the RAW returns (garch.hpp:117-118)
    instead of ``-problem->functionValue()`` over ``r2``. Those two happen to
    agree, so the fallback must reproduce the pinned guess block exactly —
    including its log-likelihood.

    ``GammaGuess`` is excluded because with a failing optimizer the
    ``mode != DoubleOptimization`` branch picks ``opt1`` whenever
    ``fCost1 <= fCost2``, and for ``GammaGuess`` ``fCost1`` is
    ``QL_MAX_REAL`` — a different, already-covered selection path.
    """
    model = Garch11(series, mode)
    model.calibrate(series, RaisingOptimizationMethod(), EndCriteria(3, 2, 0.0, 0.0, 0.0))
    _assert_calibration(model, garch[guess_key], tier="tight")


def test_a_failing_optimizer_under_gamma_guess_falls_back_to_the_gamma_guess(
    garch: dict[str, Any], series: TimeSeries[float]
) -> None:
    """``GammaGuess`` leaves ``fCost1`` at ``QL_MAX_REAL``, so ``opt2`` wins.

    # C++ parity: garch.cpp:430-440 — ``opt1`` is never even computed in this
    # mode, and garch.cpp:455-458 then selects ``opt2``.
    """
    model = Garch11(series, Garch11Mode.GammaGuess)
    model.calibrate(series, RaisingOptimizationMethod(), EndCriteria(3, 2, 0.0, 0.0, 0.0))
    _assert_calibration(model, garch["guess_gamma"], tier="tight")


def test_calibrate_with_an_explicit_initial_guess_bypasses_the_mode(
    returns: list[float], series: TimeSeries[float]
) -> None:
    """# C++ parity: garch.hpp:136-150 — the mode is not consulted at all."""
    guess = np.array([0.2, 0.2, 0.3], dtype=np.float64)
    model = Garch11(series, Garch11Mode.GammaGuess)
    model.calibrate(
        series,
        DummyOptimizationMethod(),
        EndCriteria(3, 2, 0.0, 0.0, 0.0),
        initial_guess=guess,
    )
    tolerance.exact(model.alpha(), 0.2)
    tolerance.exact(model.beta(), 0.3)
    tolerance.tight(model.omega(), 0.2)
    tolerance.tight(model.log_likelihood(), -Garch11.cost_function(returns, 0.2, 0.3, 0.2))
    # The mode is remembered even though it was not used.
    assert model.mode() is Garch11Mode.GammaGuess
