def test_omega_round_trips_through_the_vl_division(series: TimeSeries[float]) -> None:
    """``calibrate`` stores omega in ``vl_``, then divides by gamma.

    # C++ parity: garch.hpp:114-116 — ``vl_ /= gamma_`` right after
    # ``calibrate_r2`` wrote omega into it, so ``omega() == vl * gamma``
    # returns the optimizer's omega back unchanged.
    """
    model = Garch11(series, Garch11Mode.BestOfTwo)
    gamma = 1 - model.alpha() - model.beta()
    tolerance.tight(model.omega(), model.lt_vol() * gamma)


