def test_to_r2_matches_cpp(garch: dict[str, Any], returns: list[float]) -> None:
    """# C++ parity: ``Garch11::to_r2`` (garch.hpp:157-168).

    The running weight ``w /= (w + 1)`` makes this an incremental arithmetic
    mean; an exponentially weighted one would give a different number.
    """
    r2, mean_r2 = Garch11.to_r2(returns)
    assert len(r2) == len(returns)
    for got, ret in zip(r2, returns, strict=True):
        tolerance.exact(got, ret * ret)
    tolerance.tight(mean_r2, garch["mean_r2"])
    # ...and it really is the plain mean of the squares.
    tolerance.custom(
        mean_r2,
        sum(r2) / len(r2),
        abs_tol=1e-13,
        rel_tol=1e-13,
        reason="incremental vs one-shot summation of 400 terms differ in rounding only",
    )


def test_autocovariances_match_cpp(garch: dict[str, Any], returns: list[float]) -> None:
    """# C++ parity: ``autocovariances`` (ql/math/autocovariance.hpp:96-110)
    as ``calibrate_r2`` calls it (garch.cpp:415-421).

    ``ql/math/autocovariance.hpp`` has no pquantlib module yet, so the helper
    lives inside garch.py; it is pinned here because every initial guess is
    built from its output.
    """
    r2, mean_r2 = Garch11.to_r2(returns)
    max_lag = int(math.sqrt(float(len(r2))))
    assert max_lag == garch["max_lag"]
    acf = _autocovariances([x - mean_r2 for x in r2], max_lag)
    assert len(acf) == max_lag + 1
    for got, want in zip(acf, garch["acf"], strict=True):
        tolerance.tight(got, want)


