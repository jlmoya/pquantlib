    tolerance.exact(from_values.beta(), from_series.beta())
    tolerance.exact(from_values.omega(), from_series.omega())
    tolerance.exact(from_values.log_likelihood(), from_series.log_likelihood())
    _assert_calibration(from_values, garch["calibrated_best_of_two"], tier="simplex")


